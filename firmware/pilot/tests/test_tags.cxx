static Void testIntrinsics()
{
    std::printf("\n-- the calibration file: six numbers or nothing --\n");
    tags::Intrinsics cal;
    Str why;
    const Str good = "# the U20CAM at 640x480, tag 100 mm\nfx 500\nfy 510.5  # tenths\ncx 320\ncy 240\nsize 640x480\ntag 0.1\n";
    check(tags::parseIntrinsics(good, &cal, why), "a complete file parses");
    check(cal.calibrated, "and is a calibration");
    check(
        cal.fx == 500.0 && cal.fy == 510.5 && cal.cx == 320.0 && cal.cy == 240.0,
        "with its numbers"
    );
    check(
        cal.width == 640 && cal.height == 480 && cal.tagM == 0.1,
        "its frame size and the tag's size"
    );
    tags::Intrinsics untouched;
    why.clear();
    check(
        !tags::parseIntrinsics("fx 500\nfy 500\ncx 320\ncy 240\nsize 640x480\n", &untouched, why),
        "five of six is refused"
    );
    check(why == "missing tag", "and names the missing one");
    check(!untouched.calibrated && untouched.fx == 0.0, "leaving the output untouched");
    check(
        !tags::parseIntrinsics("fx 0\nfy 1\ncx 1\ncy 1\nsize 1x1\ntag 1\n", &untouched, why),
        "a zero is refused"
    );
    check(
        !tags::parseIntrinsics("fx abc\n", &untouched, why) && why.find("line 1") != Str::npos,
        "so is a word, by line"
    );
    check(
        !tags::parseIntrinsics("focal 500\n", &untouched, why) && why.find("unknown key") != Str::npos,
        "and a key nobody defined"
    );
    check(
        !tags::parseIntrinsics("size 640\n", &untouched, why) && why.find("WxH") != Str::npos,
        "and a size with no x"
    );
    check(!tags::parseIntrinsics(good, nullptr, why), "and nowhere to put it");
    check(
        tags::parseIntrinsics("", &untouched, why) == false && why == "missing fx",
        "an empty file is missing everything, fx first"
    );
    check(
        !tags::loadIntrinsics("/nonexistent/bibo/camera.txt", &untouched, why) && why.find(
            "cannot open"
        ) == 0,
        "a missing file says so"
    );
}

static Void testRefusing()
{
    std::printf("\n-- no detector in this build: every call refuses and says so --\n");
    tags::Config cfg;
    bibowire::Tags out;
    Str why;
    const Vec<UInt8> whole(TAG5.begin(), TAG5.end());
    check(!tags::find(whole, cfg, &out, why), "detect refuses");
    check(why.find("PILOT_APRILTAG") != Str::npos, "and names the configure switch");
    why.clear();
    check(!tags::start(cfg, why) && !why.empty(), "start refuses with a reason");
    check(!tags::running(), "and nothing runs");
    const tags::Stats s = tags::stats();
    check(!s.built && !s.running && !s.why.empty(), "stats say not built, not running, and why");
    tags::stop();
    check(!tags::running(), "stop is safe when nothing runs");
}

static Void testDetects()
{
    std::printf("\n-- the detector over a known picture --\n");
    tags::Config cfg;
    bibowire::Tags out;
    Str why;
    const Vec<UInt8> whole(TAG5.begin(), TAG5.end());
    check(tags::find(whole, cfg, &out, why), "a JPEG with one tag decodes and detects");
    check(out.width == 240 && out.height == 180, "with the picture's own size");
    check(out.family == bibowire::TAG_FAMILY_36H11, "in the 36h11 family");
    check(out.tags.size() == 1, "one tag");
    if(out.tags.size() == 1)
    {
        const bibowire::Tag& t = out.tags[0];
        check(t.id == 5, "id 5");
        check(t.hamming == 0, "read clean");
        check(t.marginMilli > 50000, "with a decision margin over 50");
        // The rendered tag's corners: every one on the square (80,50)..(160,130),
        // to within a pixel, in whatever order the library walks them.
        Bool onSquare = true;
        for(const bibowire::TagCorner& c : t.corners)
        {
            const Bool xOk = (c.xDeci > 790 && c.xDeci < 810) || (c.xDeci > 1590 && c.xDeci < 1610);
            const Bool yOk = (c.yDeci > 490 && c.yDeci < 510) || (c.yDeci > 1290 && c.yDeci < 1310);
            onSquare = onSquare && xOk && yOk;
        }
        check(onSquare, "and all four corners within a pixel of where it was drawn");
    }
    check(out.detectUs > 0u, "the detector's time is measured, not zero");
    check(
        out.flags == 0u && out.tags[0].rangeMm == 0 && out.tags[0].bearingCdeg == 0,
        "uncalibrated: no range, no bearing, and the flag says so"
    );
    // A made-up calibration: fx 400 at 240x180 and a 100 mm tag. The tag is 80 px
    // wide, so range is about 400 * 0.1 / 80 = 0.5 m, centred so bearing about 0.
    tags::Config known = cfg;
    known.cal.calibrated = true;
    known.cal.fx = 400.0;
    known.cal.fy = 400.0;
    known.cal.cx = 120.0;
    known.cal.cy = 90.0;
    known.cal.width = 240;
    known.cal.height = 180;
    known.cal.tagM = 0.1;
    bibowire::Tags located;
    check(
        tags::find(whole, known, &located, why) && located.tags.size() == 1,
        "with a calibration the same tag"
    );
    check(located.flags == bibowire::TAGS_FLAG_CALIBRATED, "the flag says ranges are measured");
    check(
        located.tags[0].rangeMm > 450 && located.tags[0].rangeMm < 550,
        "a 100 mm tag 80 px wide at fx 400 is about 0.5 m away"
    );
    check(
        located.tags[0].bearingCdeg > -300 && located.tags[0].bearingCdeg < 300,
        "and dead ahead, within 3 degrees"
    );
    // The same calibration at half the resolution scales with the frame.
    known.cal.fx = 800.0;
    known.cal.fy = 800.0;
    known.cal.cx = 240.0;
    known.cal.cy = 180.0;
    known.cal.width = 480;
    known.cal.height = 360;
    check(
        tags::find(whole, known, &located, why) && located.tags[0].rangeMm > 450 && located.tags[0].rangeMm < 550,
        "a calibration made at twice the size scales to this frame"
    );
    check(
        out.tMonoUs == 0u && out.frameIndex == 0u,
        "the picture's identity is left to the caller"
    );
    // Decimate 1 finds the same tag, so the default of 2 is not the only setting that works.
    cfg.decimate = 1.0f;
    bibowire::Tags full;
    check(
        tags::find(whole, cfg, &full, why) && full.tags.size() == 1 && full.tags[0].id == 5,
        "at decimate 1 the same tag"
    );
}

static Void testNothingAndJunk()
{
    std::printf("\n-- pictures with nothing in them, and bytes that are no picture --\n");
    tags::Config cfg;
    bibowire::Tags out;
    Str why;
    const Vec<UInt8> whole(TAG5.begin(), TAG5.end());
    // The first 600 bytes of the JPEG stop partway down the picture. libjpeg
    // fills what is missing and decodes, so a frame that ended early off a USB
    // camera is still a picture: the tag, drawn below the cut, is not in it,
    // and nothing exits or refuses. The size is the header's, not the bytes'.
    const Vec<UInt8> cut(TAG5.begin(), TAG5.begin() + 600);
    check(tags::find(cut, cfg, &out, why), "a truncated JPEG still decodes");
    check(out.width == 240 && out.height == 180, "at the size its header claims");
    check(out.tags.empty(), "and the tag below the cut is not found");
    const Vec<UInt8> junk = { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77 };
    check(!tags::find(junk, cfg, &out, why) && !why.empty(), "so are bytes that are no JPEG");
    check(!tags::find(Vec<UInt8>(), cfg, &out, why), "and no bytes at all");
    check(!tags::find(whole, cfg, nullptr, why), "and no place to put the answer");
    check(!tags::running(), "none of that started anything");
}

int main()
{
    std::printf("tags: the AprilTag detector\n");
    testIntrinsics();
    if(!tags::available())
    {
        std::printf("(detector NOT built: this run proves refusal only, not detection)\n");
        testRefusing();
    }
    else
    {
        testDetects();
        testNothingAndJunk();
    }
    std::printf("\n%d checks, %d failed\n\n", checks, failures);
    return failures == 0 ? 0 : 1;
}
